"""Merge every art/room-v3/<part>/manifest.json into docs/redesign/room-prototype/art-v3.js (window.ROOM_ART).

Based on scripts/room-art.py: each PNG becomes palette indices (255 = transparent), run-length encoded and
base64'd, so the prototype reads pixels without canvas taint (works from file://). Fails on any off-palette
or semi-transparent pixel, duplicate id, or a hotspot without target/label/led, and runs the grain check
(the first room's flat style): a sprite fails when too many of its pixels are isolated single pixels (no
4-neighbour of the same colour) or sit in 2x2 checkerboards (Bayer dither). Tiny sprites (LEDs, bulbs) are
exempt; the sky is allowed its dithered band edges.
Run the part builds first, then: python3 art/room-v3/merge.py
"""
import base64
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

V3 = Path(__file__).resolve().parent
COMMON = V3 / "common"
PROTO = V3.parents[1] / "docs" / "redesign" / "room-prototype"
PAL = json.loads((COMMON / "palette.json").read_text())
ZONES = json.loads((COMMON / "zones.json").read_text())
RGB = {tuple(int(h[i:i + 2], 16) for i in (1, 3, 5)): n for n, (_, h, _) in enumerate(PAL["colors"])}
PARTS = ["shell", "left", "back", "right", "statue-relics"]


def encode(path: Path) -> dict:
    im = Image.open(path).convert("RGBA")
    out = bytearray()
    run_v, run_n = None, 0
    for r, g, b, a in im.getdata():
        if a not in (0, 255):
            sys.exit(f"{path}: semi-transparent pixel")
        v = 255 if a == 0 else RGB.get((r, g, b))
        if v is None:
            sys.exit(f"{path}: off-palette pixel {(r, g, b)}")
        if v == run_v and run_n < 255:
            run_n += 1
        else:
            if run_n:
                out += bytes((run_n, run_v))
            run_v, run_n = v, 1
    out += bytes((run_n, run_v))
    return {"w": im.width, "h": im.height, "rle": base64.b64encode(bytes(out)).decode()}


# grain check: (min opaque px, max isolated share, max checkerboard share), first matching row applies
GRAIN_LIMITS = [(600, 0.15, 0.03), (150, 0.30, 0.08)]
GRAIN_EXEMPT = ("shell/sky.",)


def grain(path: Path) -> tuple[float, float, int]:
    """Share of isolated single pixels and of 2x2 checkerboard windows among a sprite's opaque pixels."""
    a = np.array(Image.open(path).convert("RGBA")).astype(np.int64)
    op = a[..., 3] == 255
    c = (a[..., 0] << 16) | (a[..., 1] << 8) | a[..., 2]
    c[~op] = -1
    n = int(op.sum())
    p = np.pad(c, 1, constant_values=-1)
    h, w = c.shape
    same = np.zeros_like(op)
    for dy, dx in ((0, 1), (2, 1), (1, 0), (1, 2)):
        same |= p[dy:dy + h, dx:dx + w] == c
    iso = int((op & ~same).sum())
    A, B, C, D = c[:-1, :-1], c[:-1, 1:], c[1:, :-1], c[1:, 1:]
    chk = int(((A >= 0) & (B >= 0) & (C >= 0) & (D >= 0) & (A == D) & (B == C) & (A != B)).sum())
    return iso / max(1, n), chk / max(1, n), n


def grain_check(paths) -> None:
    bad = []
    for rel in paths:
        if any(e in rel for e in GRAIN_EXEMPT):
            continue
        iso, chk, n = grain(PROTO / rel)
        for min_n, max_iso, max_chk in GRAIN_LIMITS:
            if n >= min_n:
                if iso > max_iso or chk > max_chk:
                    bad.append(f"{rel}: isolated {iso:.1%} (max {max_iso:.0%}), checkerboard {chk:.1%} (max {max_chk:.0%})")
                break
    if bad:
        sys.exit("grain check failed (keep flat colour clusters, no dither):\n  " + "\n  ".join(bad))
    print(f"grain check: {len(paths)} sprites ok")


def main() -> None:
    images: dict[str, dict] = {}
    items: list[dict] = []
    for part_name in PARTS:
        part = json.loads((V3 / part_name / "manifest.json").read_text())
        for it in part["items"]:
            it["part"] = part["part"]
            if it["kind"] == "hotspot" and not (it.get("target") and it.get("label") and it.get("led")):
                sys.exit(f"{it['id']}: hotspot needs target, label and led")
            for p in list(it["variants"].values()) + (it.get("anim") or {}).get("frames", []):
                if p not in images:
                    images[p] = encode(PROTO / p)
            items.append(it)
    ids = [i["id"] for i in items]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        sys.exit(f"duplicate item ids: {sorted(dupes)}")
    grain_check(sorted(images))
    bundle = {"version": 3, "palette": PAL, "zones": ZONES, "items": items, "images": images}
    out = PROTO / "art-v3.js"
    out.write_text("// GENERATED by art/room-v3/merge.py from art/room-v3/*/build.py output.\nwindow.ROOM_ART = "
                   + json.dumps(bundle, separators=(",", ":")) + ";\n")
    kinds = {k: sum(1 for i in items if i["kind"] == k) for k in ("shell", "hotspot", "decor", "overlay")}
    print(f"{len(items)} items {kinds}, {len(images)} images, art-v3.js {out.stat().st_size // 1024} KB")
    per_zone = {}
    for i in items:
        if i["kind"] == "decor":
            per_zone[i["zone"]] = per_zone.get(i["zone"], 0) + 1
    print("decor per zone:", per_zone)


if __name__ == "__main__":
    main()
