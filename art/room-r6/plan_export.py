"""Admin floor plan (v3.5 admin view, PLAN Phase 1): a top-down footprint of the room for /admin.

Writes art/room-r6/plan.json and public/room/plan.json:
  {room: {w, d, x0, z0}, walls: [{side, x0, z0, x1, z1}], openings: [{kind, wall, x0, z0, x1, z1}],
   ceiling: [{kind, x0, z0, x1, z1}], objects: [{id, kind, x0, z0, x1, z1, y0, h, wall, zone, label, target}]}
World feet: X runs left to right facing the window, Z runs from the back wall (-14) to the window wall (+14).

Footprints come from B.box_table() (build.py, PLAN 2.6) via boxes.json, which build.py dumps from box_table() on every
build. Reading that dump instead of calling box_table() here is deliberate: box_table() needs the base and ghost
renders of all four views (the ~10 minute part of the build) and gives the same numbers. build.py calls export() right
after it writes boxes.json, so a full build keeps plan.json in step; run this file alone after a build to refresh it.
Targets, labels and zones come from manifest.json; the window, door and skylight from build.py's constants.

Usage: python3 art/room-r6/plan_export.py [--boxes path/to/boxes.json]
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))

RS = 14.0                         # build.py RS: walls at X, Z = +-RS
WIN = (-1.8, 8.6)                 # build.py WIN: window X0, X1 on the front wall
DOOR_Z = (-11.0, -7.8)            # build.py kitchen 'door' obj: local x -8.4..-5.2 shifted -2.6, left wall (Z = local x)
SKYLIGHT = (-3.0, 3.0, 2.6, 6.6)  # build.py SKYLIGHT: X0, X1, Z0, Z1
WALL_EPS = 0.25                   # a box within this of a wall plane is wall mounted


def wall_of(b):
    """Which wall a box (X0, Y0, Z0, X1, Y1, Z1) hangs on, or None for a floor object."""
    X0, Y0, Z0, X1, Y1, Z1 = b
    near = []
    if X1 >= RS - WALL_EPS:
        near.append(("right", X1 - X0))
    if X0 <= -RS + WALL_EPS:
        near.append(("left", X1 - X0))
    if Z1 >= RS - WALL_EPS:
        near.append(("front", Z1 - Z0))
    if Z0 <= -RS + WALL_EPS:
        near.append(("back", Z1 - Z0))
    # thin against the wall (a card, a shelf) or raised off the floor: mounted
    near = [s for s, depth in near if depth <= 1.0 or Y0 > 1.5]
    return near[0] if near else None


def build(boxes, manifest):
    items = {r["id"]: r for r in manifest if r.get("kind") == "hotspot" and r.get("view") != "top"}
    objects = []
    for hid, b in sorted(boxes.items()):
        it = items.get(hid)
        if it is None:
            continue
        X0, Y0, Z0, X1, Y1, Z1 = b["world"]
        # a box can spill a hair past the wall plane; clamp it into the room
        X0, X1 = max(-RS, X0), min(RS, X1)
        Z0, Z1 = max(-RS, Z0), min(RS, Z1)
        objects.append({
            "id": hid, "kind": b["kind"], "src": b["src"],
            "x0": round(X0, 2), "z0": round(Z0, 2), "x1": round(X1, 2), "z1": round(Z1, 2),
            "y0": round(max(0.0, Y0), 2), "h": round(Y1 - max(0.0, Y0), 2),
            "wall": wall_of((X0, Y0, Z0, X1, Y1, Z1)), "view": b["view"], "zone": it.get("zone"),
            "label": it.get("label") or hid, "target": it.get("target"),
        })
    missing = sorted(set(items) - {o["id"] for o in objects})
    return {
        "_note": "GENERATED by art/room-r6/plan_export.py from boxes.json (B.box_table) + manifest.json. World ft.",
        "room": {"w": 2 * RS, "d": 2 * RS, "x0": -RS, "z0": -RS},
        "walls": [
            {"side": "back", "x0": -RS, "z0": -RS, "x1": RS, "z1": -RS},
            {"side": "right", "x0": RS, "z0": -RS, "x1": RS, "z1": RS},
            {"side": "front", "x0": RS, "z0": RS, "x1": -RS, "z1": RS},
            {"side": "left", "x0": -RS, "z0": RS, "x1": -RS, "z1": -RS},
        ],
        "openings": [
            {"kind": "window", "wall": "front", "x0": WIN[0], "z0": RS, "x1": WIN[1], "z1": RS},
            {"kind": "door", "wall": "left", "x0": -RS, "z0": DOOR_Z[0], "x1": -RS, "z1": DOOR_Z[1]},
        ],
        "ceiling": [{"kind": "skylight", "x0": SKYLIGHT[0], "z0": SKYLIGHT[2], "x1": SKYLIGHT[1], "z1": SKYLIGHT[3]}],
        "objects": objects,
        "missing": missing,
    }


def write(plan):
    for path in (os.path.join(HERE, "plan.json"), os.path.join(ROOT, "public", "room", "plan.json")):
        with open(path, "w") as f:
            json.dump(plan, f, indent=1)
            f.write("\n")
    return plan


def export(B=None, manifest=None):
    """build.py hook: B is the build module (its box_table() is cached by then)."""
    if B is not None:
        boxes = B.box_table()
    else:
        with open(os.path.join(HERE, "boxes.json")) as f:
            boxes = json.load(f)["boxes"]
    if manifest is None:
        with open(os.path.join(HERE, "manifest.json")) as f:
            manifest = json.load(f)["items"]
    plan = write(build(boxes, manifest))
    if plan["missing"]:
        print(f"plan.json: no footprint for {plan['missing']}")
    return plan


if __name__ == "__main__":
    boxes_path = sys.argv[sys.argv.index("--boxes") + 1] if "--boxes" in sys.argv else os.path.join(HERE, "boxes.json")
    with open(boxes_path) as f:
        bx = json.load(f)["boxes"]
    with open(os.path.join(HERE, "manifest.json")) as f:
        man = json.load(f)["items"]
    p = write(build(bx, man))
    print(f"plan.json: {len(p['objects'])} objects, missing {p['missing']}")
    for o in p["objects"]:
        print(f"  {o['id']:22} {o['wall'] or 'floor':6} [{o['x0']:6.2f},{o['z0']:6.2f}]..[{o['x1']:6.2f},{o['z1']:6.2f}]")
