#!/usr/bin/env node
/**
 * Writes docs/redesign/room-prototype/lyfta.js (window.ROOM_LYFTA): the strength hologram's summary of the owner's
 * real Lyfta workouts (src/lib/data/lyftaSummary.ts; same mapping as the approved gym mockup).
 *   NODE_USE_ENV_PROXY=1 node scripts/room-lyfta-snapshot.mjs [--in raw.json] [--today YYYY-MM-DD]
 *   (NODE_USE_ENV_PROXY makes Node's fetch use HTTPS_PROXY behind the agent proxy)
 * Calls https://my.lyfta.app/api/v1/workouts. No Authorization header is sent unless LYFTA_API_KEY is set: in the
 * agent sessions the network proxy injects the key. --in reads a saved response ({workouts: [...]}) instead.
 * PERSONAL DATA: the file is for the prototype pages and their artifacts only. scripts/room-sync.mjs never copies it
 * to public/room; the app gets the same shape from the server (src/lib/data/room.ts).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { tsImport } from "tsx/esm/api";

const L = await tsImport("../src/lib/data/lyftaSummary.ts", import.meta.url);
const arg = (k) => {
  const i = process.argv.indexOf(k);
  return i > 0 ? process.argv[i + 1] : null;
};
const input = arg("--in");
const workouts = input ? JSON.parse(readFileSync(input, "utf8")).workouts : await L.fetchLyftaWorkouts(process.env.LYFTA_API_KEY || null);
const today = arg("--today") || L.localToday();
const fetched = new Date().toISOString().slice(0, 16).replace("T", " ") + " UTC";
const out = L.summarizeLyfta(workouts, { today, fetched });
const file = join(import.meta.dirname, "..", "docs", "redesign", "room-prototype", "lyfta.js");
writeFileSync(
  file,
  `// GENERATED by scripts/room-lyfta-snapshot.mjs from the Lyfta API. The owner's real workouts: prototype pages and\n` +
    `// artifacts only (never public/room). Day boundary ${out.timezone}; ${out.schedule.plannedPerWeek} planned lifts a week (assumed).\n` +
    `window.ROOM_LYFTA = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(`lyfta.js: ${workouts.length} workouts, week of ${out.weekStart}, ${out.schedule.doneThisWeek}/${out.schedule.plannedPerWeek} lifts, as of ${today}`);
