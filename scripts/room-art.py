"""Merge every art/room/<part>/manifest.json into docs/redesign/room-prototype/art.js.

Each PNG is converted to palette indices (255 = transparent), run-length encoded and base64'd, so the
prototype can read pixels without canvas taint (it also works from file://). Fails on any off-palette
pixel. Run: python3 scripts/room-art.py   (after running the parts' build.py scripts)
"""
import base64
import json
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
COMMON = ROOT / "art" / "room" / "common"
PROTO = ROOT / "docs" / "redesign" / "room-prototype"
PAL = json.loads((COMMON / "palette.json").read_text())
ZONES = json.loads((COMMON / "zones.json").read_text())
RGB = {tuple(int(h[i : i + 2], 16) for i in (1, 3, 5)): n for n, (_, h, _) in enumerate(PAL["colors"])}


def encode(path: Path) -> dict:
    im = Image.open(path).convert("RGBA")
    out = bytearray()
    run_v, run_n = None, 0
    for r, g, b, a in im.getdata():
        v = 255 if a == 0 else RGB.get((r, g, b))
        if v is None:
            sys.exit(f"{path}: off-palette pixel {(r, g, b)}")
        if v == run_v and run_n < 255:
            run_n += 1
        else:
            if run_n:
                out += bytes((run_n, run_v))
            run_v, run_n = v, 1
    out += bytes((run_n, run_v))
    return {"w": im.width, "h": im.height, "rle": base64.b64encode(bytes(out)).decode()}


def main() -> None:
    images: dict[str, dict] = {}
    items: list[dict] = []
    for mf in sorted((ROOT / "art" / "room").glob("*/manifest.json")):
        part = json.loads(mf.read_text())
        for it in part["items"]:
            it["part"] = part["part"]
            paths = list(it["variants"].values()) + (it.get("anim") or {}).get("frames", [])
            for p in paths:
                if p not in images:
                    images[p] = encode(PROTO / p)
            items.append(it)
    ids = [i["id"] for i in items]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        sys.exit(f"duplicate item ids: {sorted(dupes)}")
    bundle = {"palette": PAL, "zones": ZONES, "items": items, "images": images}
    (PROTO / "art.js").write_text("// GENERATED by scripts/room-art.py from art/room/*/build.py output.\nwindow.ROOM_ART = " + json.dumps(bundle, separators=(",", ":")) + ";\n")
    size = (PROTO / "art.js").stat().st_size
    print(f"{len(items)} items, {len(images)} images, art.js {size // 1024} KB")


if __name__ == "__main__":
    main()
